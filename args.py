import argparse
def get_args():
    parser = argparse.ArgumentParser(description='Description of your program')
    parser.add_argument('--debug', action="store_true", help="Set this flag to True to pass wandb")
    parser.add_argument('--wandb_profile',type=str, default = 'attentionrl')
    parser.add_argument('--project_name',type=str, default = "pytorch-sweeps-demo")
    parser.add_argument('--run_name',type=str, default = None)
    parser.add_argument('--p', type=float, default=0.05)
    parser.add_argument('--q', type=float, default=0.05)
    parser.add_argument('--features_num', type=int, default=5,help='Used for CSBM')
    parser.add_argument('--mu',nargs='+', type=float, default=[0.0])
    parser.add_argument('--aggr_methode',type=str,default='Default',choices=['Default','add','mean','max','min'],help='The aggregation method to use for GNNs')
    parser.add_argument('--num_runs', type=int, default=10,help='Number of runs for a single settings')
    parser.add_argument('--model_type', type=str,required=True,choices=['GCN','GAT','SAGE','GIN','H2GCN','custom_GCN'],help='Choose a SINGLE model type to use')
    parser.add_argument('--loss_type', type=str, default='normal',choices=['normal','bs','focal','tilted'],help='The type of loss used')
    parser.add_argument('--titled_tea', type=int, default=None,help='The T value in tilted loss')
    parser.add_argument('--focal_gamma', type=float, default=None,help='The gamma value in focal loss')
    parser.add_argument('--num_augmentations', default=100, type=int, help="Number of augmented graphs in the uncertainty process")
    parser.add_argument('--nums_to_remove', default=100, type=int, help="Number of augmented graphs in the uncertainty process")

    parser.add_argument('--imbal_coef',type=float, default = 10,help='Imbalance ratio')
    parser.add_argument('--num_threads',type=int, default = 10,help='Number of threads to use for computing the graphs, maximum should be the number of cores')
    parser.add_argument('--lr',type=float,default=0.01,help='The learning rate')
    parser.add_argument('--wd',type=float,default=5e-4,help='The weight decay')
    parser.add_argument('--hidden_channels',type=int,default=256,help='The hidden channels')
    parser.add_argument('--num_heads',type=int,default=4,help='The number of heads for GAT')
    parser.add_argument('--weight_decay',type=float,default=5e-4,help='The weight decay')
    parser.add_argument('--use_scheduler', action="store_true", help="Set this flag to True to use the learning rate scheduler")
    parser.add_argument('--schedule_factor',type=float,default=0.5,help='The factor to reduce the learning rate')
    parser.add_argument('--schedule_patience',type=int,default=100,help='The patience for the learning rate scheduler')
    parser.add_argument('--regularizer',type=str, default = None,choices=['kl','kl_reverse'],help='Choose the regularizer to use')
    parser.add_argument('--regularizer_coef',type=float, default = 0.5,help='The coefficient of the regularizer')
    parser.add_argument('--kl_power',type=float, default = 1)
    parser.add_argument('--special_title',type=str,nargs='+', default = '')
    parser.add_argument('--notes',type=str,nargs='+', default = '')
    parser.add_argument('--patience',type=int, default = 100,help='The patience for early stopping')

    parser.add_argument('--data_set',type=str, default = 'synthetic')
    parser.add_argument('--data_path',type=str, default = 'data')
    parser.add_argument('--edge_temper_presets',type=str, default = 'all',choices=['all','io','ibn'])
    parser.add_argument('--pca_dim',type=int, default = 0)
    parser.add_argument('--lda_dim',type=int, default = 0)
    parser.add_argument('--device',type=str, default = 'cuda')
    parser.add_argument('--num_extra_runs',type=int, default = 0,help='Number of runs where a constant number of pseudo labels are added')
    parser.add_argument('--pseudo_thr_band',type=float, default = 0.5,help='Lenght of the band for pseudo labeling threshold')
    parser.add_argument('--pseudo_labels_thr',type=float,nargs='+',help='Number of pseudo labels to add in each run')
    parser.add_argument('--ens',action="store_true",help="Set this flag to activate the ENS model")
    parser.add_argument('--pred_temp',type=float, default = 2,help='Prediction temperature')
    parser.add_argument('--keep_prob',type=float, default = 0.01,help='Keeping Probability')
    parser.add_argument('--predictor',type = str, default = 'hh',choices=['hh','jacard','academic'])
    parser.add_argument('--generator',type = str, default = 'random_link',choices=['random_link'])
    parser.add_argument('--top_percent_link',type = float, default = 0)
    ##TAM###
    parser.add_argument('--tam',action="store_true",help="Set this flag to activate the TAM regularizer")
    parser.add_argument('--warm_up',type=int, default = 5)
    parser.add_argument('--tam_alpha', type=float, default=2.5,help='coefficient of ACM')
    parser.add_argument('--tam_beta', type=float, default=0.5,help='coefficient of ADM')
    parser.add_argument('--temp_phi', type=float, default=1.2,help='classwise temperature')
    
    parser.add_argument('--pseudo_labeler', default='fixed',type=str,choices=['flex_match','fixed'],help='Choose a SINGLE model type to use')
    parser.add_argument('--mapping', default = 'convex',type=str,choices=['convex'],help='Choose a SINGLE model type to use')

    # parser.add_argument('--uncertain_thr',type=float, default = 1,help='Uncertainty Threshold')
    
    parser.add_argument('--entropy_uncertainty_percent', type=float, default=0.9,help='Percent of nodes to pick based on entropy')
    parser.add_argument('--entropy_uncertainty',action="store_true",help="whether to use uncertainty with the help of entropy")
    parser.add_argument('--uncertainty',action="store_true",help="whether to use uncertainty")
    parser.add_argument('--change_order',default=None,type=int,nargs='+',help='Change the order of the classes')
    parser.add_argument('--classes_to_keep',default=None,type=int,nargs='+',help='Keep only the chosen classes')
    
    
    args = parser.parse_args()
    return args